        const title = modal.querySelector('#inventory-confirm-title');
        const message = modal.querySelector('#inventory-confirm-message');
        const confirmButton = modal.querySelector('[data-confirm-submit]');
        const cancelButtons = modal.querySelectorAll('[data-confirm-cancel]');
        const approvedForms = new WeakSet();
        let pendingSubmission = null;
        let previousFocus = null;

        document.querySelectorAll('form[onsubmit]').forEach((form) => {
            const handler = form.getAttribute('onsubmit') || '';
            const match = handler.match(/confirm\((['"])(.*?)\1\)/);
            if (!match) return;

            form.dataset.confirmMessage = match[2]
                .replace(/^Â?¿/, '')
                .replace(/\?$/, '')
                .trim();
            form.removeAttribute('onsubmit');
        });

        const closeModal = () => {
            modal.hidden = true;
            document.body.classList.remove('has-confirm-modal');
            pendingSubmission = null;
            if (previousFocus instanceof HTMLElement) previousFocus.focus();
        };

        const approveSubmission = () => {
            if (!pendingSubmission) return;
            const { form, submitter } = pendingSubmission;
            modal.hidden = true;
            document.body.classList.remove('has-confirm-modal');
            pendingSubmission = null;
            approvedForms.add(form);
            form.requestSubmit(submitter || undefined);
        };

        document.addEventListener('submit', (event) => {
            const form = event.target;
            if (!(form instanceof HTMLFormElement) || !form.dataset.confirmMessage) return;
            if (approvedForms.has(form)) {
                approvedForms.delete(form);
                return;
            }

            event.preventDefault();
            previousFocus = document.activeElement;
            pendingSubmission = { form, submitter: event.submitter };
            const actionText = form.dataset.confirmMessage;
            title.textContent = actionText.startsWith('Eliminar')
                ? `¿${actionText}?`
                : '¿Confirmar eliminación?';
            message.textContent = 'Esta acción es permanente y no se puede deshacer. Verifica que seleccionaste el elemento correcto antes de continuar.';
            modal.hidden = false;
            document.body.classList.add('has-confirm-modal');
            window.requestAnimationFrame(() => confirmButton.focus());
        }, true);

        confirmButton.addEventListener('click', approveSubmission);
        cancelButtons.forEach((button) => button.addEventListener('click', closeModal));
        document.addEventListener('keydown', (event) => {
            if (modal.hidden) return;
            if (event.key === 'Escape') closeModal();
        });
    })();
    </script>
